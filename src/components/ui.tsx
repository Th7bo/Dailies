import clsx from "clsx";
import Link from "next/link";
import type { ComponentProps } from "react";

export const cn = clsx;

const base =
  "inline-flex items-center justify-center gap-2 rounded-full font-medium transition-colors disabled:cursor-not-allowed disabled:opacity-50 whitespace-nowrap";
const variants = {
  sun: "bg-sun text-night-deep hover:bg-sun-deep",
  ghost: "text-paper hover:bg-dusk",
  outline: "border border-rim text-paper hover:border-haze hover:bg-dusk",
  danger: "border border-coral/40 text-coral hover:bg-coral/10",
  discord: "bg-[#5865F2] text-white hover:bg-[#4752c4]",
} as const;
const sizes = { sm: "h-8 px-3 text-sm", md: "h-10 px-4 text-sm", lg: "h-12 px-6 text-base" } as const;

type Variant = keyof typeof variants;
type Size = keyof typeof sizes;

export function buttonClass(variant: Variant = "outline", size: Size = "md", extra?: string) {
  return cn(base, variants[variant], sizes[size], extra);
}

export function Button({
  variant,
  size,
  className,
  ...props
}: ComponentProps<"button"> & { variant?: Variant; size?: Size }) {
  return <button className={buttonClass(variant, size, className)} {...props} />;
}

export function ButtonLink({
  variant,
  size,
  className,
  ...props
}: ComponentProps<typeof Link> & { variant?: Variant; size?: Size }) {
  return <Link className={buttonClass(variant, size, className)} {...props} />;
}

